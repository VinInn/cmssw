#ifndef DataFormatsMathfastRandomNormal_H
#define DataFormatsMathfastRandomNormal_H

#include "DataFormats/Math/interface/fastRandomTwoSingle.h"
#include "DataFormats/Math/interface/approx_log.h"

#ifdef USE_VDT
#include <vdt/sincos.h>
template <typename Float>
inline std::tuple<Float, Float> approx_sincos(Float x) {
  Float s, c;
  vdt::fast_sincosf(x, s, c);
  return {s, c};
}
#else
#include "DataFormats/Math/interface/approx_sincos.h"
#endif

#include <tuple>
#include <cmath>

namespace fastRandom {
  // generate two normal distributed single precision number (mean 0, variance 1) from a flat random double in [0,1[ (as for instance generated by CLHEP engine)
  inline std::tuple<float, float> normal(double d) {
    auto [x, y] = twoSingle(d);
    constexpr float pif = M_PI;
    constexpr float pi2f = 2.0 * M_PI;
    // unsafe_log is very safe here as it cannot return neither Nan nor -inf
    float u = std::sqrt(-2.f * unsafe_logf<6>(x));
    auto [s, c] = approx_sincos(pi2f * y - pif);
    return {u * c, u * s};
  }
}  // namespace fastRandom
#endif
